// Generates lib/src/asmjit/x86/x86_rw_info.g.dart from
// assets/db/x86_rwinfo.txt (copied from upstream x86instdb.cpp by
// tool/vendor_x86_rwinfo.dart).
//
// Upstream indexes the tables by its own instruction ids; the Dart ids
// (X86InstId) are assigned by tool/gen_x86_db.dart, so the per-instruction
// rows are re-indexed by instruction name.
//
// Usage: dart run tool/gen_x86_rwinfo.dart
import 'dart:io';

import 'package:asmjit/src/asmjit/x86/x86_inst_db.g.dart';

const _opFlags = {
  'None': 0x00000000,
  'Read': 0x00000001,
  'Write': 0x00000002,
  'RW': 0x00000003,
  'RegMem': 0x00000004,
  'Consecutive': 0x00000008,
  'ZExt': 0x00000010,
  'Unique': 0x00000080,
  'RegPhysId': 0x00000100,
  'MemPhysId': 0x00000200,
  'MemFake': 0x00000400,
  'MemBaseRead': 0x00001000,
  'MemBaseWrite': 0x00002000,
  'MemBaseRW': 0x00003000,
  'MemIndexRead': 0x00004000,
  'MemIndexWrite': 0x00008000,
  'MemIndexRW': 0x0000C000,
  'MemBasePreModify': 0x00010000,
  'MemBasePostModify': 0x00020000,
};

const _rwCategories = [
  'Generic',
  'GenericEx',
  'Mov',
  'Movabs',
  'Imul',
  'Movh64',
  'Punpcklxx',
  'Vmaskmov',
  'Vmovddup',
  'Vmovmskpd',
  'Vmovmskps',
  'Vmov1_2',
  'Vmov1_4',
  'Vmov1_8',
  'Vmov2_1',
  'Vmov4_1',
  'Vmov8_1',
];

const _rmCategories = [
  'None',
  'Fixed',
  'Consistent',
  'Half',
  'Quarter',
  'Eighth',
];

const _rmFlags = {
  'FlagAmbiguous': 0x01,
  'FlagPextrw': 0x02,
  'FlagMovssMovsd': 0x04,
  'FlagFeatureIfRMI': 0x08,
};

// `InstControlFlow` and `InstSameRegHint` (asmjit/core/inst.h).
const _controlFlow = ['Regular', 'Jump', 'Branch', 'Call', 'Return'];
const _sameRegHint = ['None', 'RO', 'WO'];

String _hex(int v, [int width = 0]) =>
    '0x${v.toRadixString(16).toUpperCase().padLeft(width, '0')}';

void main() {
  final lines = File('assets/db/x86_rwinfo.txt')
      .readAsLinesSync()
      .where((l) => l.isNotEmpty && !l.startsWith('#'))
      .map((l) => l.split(';'))
      .toList();

  final byName = {for (final i in kX86InstDb) i.name: i.id};
  final inst = List<int>.filled(kX86InstDb.length, 0);
  final seen = <int>{};
  for (final r in lines.where((r) => r[0] == 'I')) {
    if (r[1] == 'None') continue;
    final id = byName[r[1].toLowerCase()];
    if (id == null) throw StateError('unknown instruction ${r[1]}');
    final cf = _controlFlow.indexOf(r[5]);
    final srh = _sameRegHint.indexOf(r[6]);
    if (cf < 0 || srh < 0) throw StateError('bad row $r');
    inst[id] = int.parse(r[2]) |
        (int.parse(r[3]) << 8) |
        ((r[4] == 'MovOp' ? 1 : 0) << 16) |
        (cf << 17) |
        (srh << 20);
    seen.add(id);
  }
  final missing = [
    for (final i in kX86InstDb)
      if (!seen.contains(i.id)) i.name
  ];

  final out = StringBuffer()
    ..writeln('// GENERATED FILE - DO NOT EDIT')
    ..writeln('// Generated by tool/gen_x86_rwinfo.dart')
    ..writeln('// Source: assets/db/x86_rwinfo.txt (upstream x86instdb.cpp)')
    ..writeln()
    ..writeln("import 'x86_rw_info.dart';")
    ..writeln()
    ..writeln('/// Per instruction ([X86InstId]): rw_info_index_a (bits 0-7),')
    ..writeln('/// rw_info_index_b (8-15), `InstRWFlags::kMovOp` (16),')
    ..writeln('/// `InstControlFlow` (17-19) and `InstSameRegHint` (20-21).')
    ..writeln('const List<int> kX86InstRwData = <int>[');
  for (var i = 0; i < inst.length; i++) {
    out.writeln('  ${_hex(inst[i])}, // ${kX86InstDb[i].name}');
  }
  out.writeln('];');
  if (missing.isNotEmpty) {
    out.writeln('// Not in upstream: ${missing.join(', ')}');
  }

  for (final (tag, name) in [
    ('A', 'kX86RwInfoA'),
    ('B', 'kX86RwInfoB'),
  ]) {
    out
      ..writeln()
      ..writeln('/// `InstDB::rw_info_${tag.toLowerCase()}_table`.')
      ..writeln('const List<X86RWInfo> $name = <X86RWInfo>[');
    for (final r in lines.where((r) => r[0] == tag)) {
      final cat = _rwCategories.indexOf(r[1]);
      if (cat < 0) throw StateError('bad category $r');
      out.writeln('  X86RWInfo($cat, ${r[2]}, [${r.sublist(3).join(', ')}]),');
    }
    out.writeln('];');
  }

  out
    ..writeln()
    ..writeln('/// `InstDB::rw_info_op_table`.')
    ..writeln('const List<X86RWInfoOp> kX86RwInfoOp = <X86RWInfoOp>[');
  for (final r in lines.where((r) => r[0] == 'O')) {
    var flags = 0;
    for (final f in r[5].split('|')) {
      final v = _opFlags[f];
      if (v == null) throw StateError('bad op flag $f');
      flags |= v;
    }
    // The byte masks are 64-bit (emitted as unsigned hex literals).
    out.writeln('  X86RWInfoOp(0x${r[1]}, 0x${r[2]}, '
        '${_hex(int.parse(r[3], radix: 16))}, ${r[4]}, ${_hex(flags)}),');
  }
  out.writeln('];');

  out
    ..writeln()
    ..writeln('/// `InstDB::rw_info_rm_table` (the feature is the name of the')
    ..writeln('/// `CpuFeatures::X86` value, empty when none).')
    ..writeln('const List<X86RWInfoRm> kX86RwInfoRm = <X86RWInfoRm>[');
  for (final r in lines.where((r) => r[0] == 'R')) {
    final cat = _rmCategories.indexOf(r[1]);
    if (cat < 0) throw StateError('bad rm category $r');
    var flags = 0;
    if (r[4] != '0') {
      for (final f in r[4].split('|')) {
        flags |= _rmFlags[f] ?? (throw StateError('bad rm flag $f'));
      }
    }
    final feature = r[5] == '0' ? '' : r[5];
    out.writeln('  X86RWInfoRm($cat, ${_hex(int.parse(r[2], radix: 16))}, '
        "${r[3]}, $flags, '$feature'),");
  }
  out.writeln('];');

  File('lib/src/asmjit/x86/x86_rw_info.g.dart')
      .writeAsStringSync(out.toString());
  stdout.writeln('lib/src/asmjit/x86/x86_rw_info.g.dart written '
      '(${missing.length} instructions not in upstream)');
}
