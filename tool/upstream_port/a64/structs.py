import re
R='/Volumes/ssd_dock/MyProjectsDart/asmjit/referencias/asmjit-master/asmjit/arm/'
src=open(R+'a64instdb_p.h').read().split('\n')

# Upstream signatures (OperandSignature): opType(0) regType(3) regGroup(8) size(24); element type at 12.
RT={'kGp32':5,'kGp64':6,'kVec8':7,'kVec16':8,'kVec32':9,'kVec64':10,'kVec128':11}
SZ={'kGp32':4,'kGp64':8,'kVec8':1,'kVec16':2,'kVec32':4,'kVec64':8,'kVec128':16}
GRP={'kGp32':0,'kGp64':0}
def sig(rt): return 1 | (RT[rt]<<3) | (GRP.get(rt,1)<<8) | (SZ[rt]<<24)
ET={'kNone':0,'kB':1,'kH':2,'kS':3,'kD':4,'kB4':5,'kH2':6}

out=[]
consts={}
def emit_const(name, val, comment=''):
    consts[name]=val
    out.append(f'const int {name} = {val};' + (f' // {comment}' if comment else ''))

def cval(expr):
    expr=expr.strip()
    m=re.match(r'^RegTraits<RegType::(\w+)>::kSignature$', expr)
    if m: return hex(sig(m.group(1)))
    m=re.match(r'^uint8_t\(VecElementType::(\w+)\)$', expr)
    if m: return str(ET[m.group(1)])
    m=re.match(r'^(\w+) \| Vec::kSignatureElement(\w+)$', expr)
    if m: return hex(int(consts[m.group(1)],0) | (ET['k'+m.group(2)]<<12))
    if expr=='Gp::kIdZr': return '63'
    if expr=='Gp::kIdSp': return '31'
    if expr in consts: return consts[expr]
    return expr.rstrip('u')

i=0
mode=None
structs=[]
while i < len(src):
    l=src[i]
    s=re.sub(r'//.*','',l).strip()
    m=re.match(r'^static constexpr uint32_t (\w+) = (.+);$', s)
    if m:
        emit_const(m.group(1), cval(m.group(2))); i+=1; continue
    m=re.match(r'^enum (\w+)\s*(:\s*\w+)?\s*\{$', s)
    if m and m.group(1)!='EncodingId':
        out.append(f'\n// enum {m.group(1)}')
        v=0; i+=1
        while not src[i].strip().startswith('};'):
            e=re.sub(r'//.*','',src[i]).strip().rstrip(',')
            if e:
                mm=re.match(r'^(\w+)\s*=\s*(.+)$', e)
                if mm:
                    val=cval(mm.group(2)); emit_const(mm.group(1), val)
                    try: v=int(val,0)+1
                    except: v=None
                else:
                    emit_const(e, str(v)); v+=1
            i+=1
        i+=1; continue
    m=re.match(r'^struct (\w+) \{$', s)
    if m:
        name=m.group(1); fields=[]; getters=[]; i+=1
        while not src[i].strip().startswith('};'):
            t=re.sub(r'//.*','',src[i]).strip()
            mm=re.match(r'^M_OPCODE\((\w+), (\d+)\)$', t)
            if mm: fields.append(('_'+mm.group(1),'int')); getters.append(f'  int get {mm.group(1)} => (_{mm.group(1)} << {32-int(mm.group(2))}) & 0xFFFFFFFF;')
            mm=re.match(r'^(uint32_t|uint16_t|uint8_t|bool|OffsetType|int32_t)\s+(\w+)\s*(:\s*\d+)?;$', t)
            if mm: fields.append((mm.group(2), 'bool' if mm.group(1)=='bool' else 'int'))
            mm=re.match(r'^constexpr uint32_t (\w+)\(\) const noexcept \{ return (.*); \};?$', t)
            if mm:
                body=mm.group(2).replace('uint32_t(','(').replace('0x5u','0x5')
                getters.append(f'  int get {mm.group(1)} => ({body}) & 0xFFFFFFFF;')
            if t and not mm and not t.startswith(('M_OPCODE','uint','bool','OffsetType','int32','constexpr')):
                print('WARN struct', name, t)
            i+=1
        structs.append(name)
        ctor=', '.join(f'this.{f}' for f,_ in fields)
        out.append(f'\n/// `{name}`.\nfinal class {name} {{')
        for f,t in fields: out.append(f'  final {t} {f};')
        out.append(f'  const {name}({ctor});')
        out.extend(getters)
        out.append('}')
        i+=1; continue
    m=re.match(r'^using (\w+) = (\w+);$', s)
    if m:
        out.append(f'typedef {m.group(1)} = {m.group(2)};'); i+=1; continue
    i+=1

body='\n'.join(out)
# camelCase fields: keep upstream snake_case names (the translated assembler uses them).
hdr='''// Port of asmjit/arm/a64instdb_p.h and a64instdb.h: instruction database
// constants and the `EncodingData` structs used by the AArch64 encoder
// (a64_emit.dart). Field and constant names keep upstream spelling so the
// encoder can be diffed against upstream.
//
// The data arrays are generated by tool/gen_a64_db.dart into
// a64_encoding_data.g.dart.

// ignore_for_file: constant_identifier_names, non_constant_identifier_names
'''
open('/Volumes/ssd_dock/MyProjectsDart/asmjit/lib/src/asmjit/arm/a64_instdb.dart','w').write(hdr+body+'\n')
print(len(structs),'structs')
