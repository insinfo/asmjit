// Generates lib/src/asmjit/arm/a64_encoding_data.g.dart (the AArch64 encoder
// tables) from the upstream data copied by tool/vendor_a64_instdb.dart:
//
//   - kA64UpInstNames / kA64UpInstInfo: the upstream instruction table
//     (`InstDB::_inst_info_table`), indexed by upstream instruction id;
//   - one array per `EncodingData` struct (`baseAddSub`, `simdLdSt`, ...).
//
// Usage: dart run tool/gen_a64_encoder.dart
import 'dart:io';

import 'package:asmjit/src/asmjit/arm/a64_instdb.dart';

const _out = 'lib/src/asmjit/arm/a64_encoding_data.g.dart';

void main() => generateA64Encoder();

void generateA64Encoder({
  String instdbPath = 'assets/db/a64_instdb.txt',
  String dataPath = 'assets/db/a64_encoding_data.txt',
}) {
  final rows = [
    for (final l in File(instdbPath).readAsLinesSync())
      if (!l.startsWith('#') && l.isNotEmpty) l.split(';')
  ];
  final ids = {for (final (i, r) in rows.indexed) r[0]: i};

  String value(String t) {
    t = t.trim();
    if (t.startsWith('0b')) {
      return '0x${int.parse(t.substring(2), radix: 2).toRadixString(16)}';
    }
    final inst = RegExp(r'^Inst::kId(\w+)$').firstMatch(t);
    if (inst != null) return '${ids[inst[1]]!} /* ${inst[1]} */';
    // 1-bit fields are ints in the Dart structs.
    if (t == 'true') return '1';
    if (t == 'false') return '0';
    if (t.startsWith('OffsetType::')) {
      return 'A64OffsetType.${t.substring(12)}';
    }
    return t;
  }

  final sb = StringBuffer()
    ..writeln('// GENERATED FILE - DO NOT EDIT')
    ..writeln('// Generated by tool/gen_a64_encoder.dart')
    ..writeln('// Source: assets/db/a64_instdb.txt, '
        'assets/db/a64_encoding_data.txt (upstream a64instdb.cpp)')
    ..writeln()
    ..writeln("import 'a64_instdb.dart';")
    ..writeln()
    ..writeln('/// Upstream instruction names (lowercase, `_v` = vector form), '
        'indexed by upstream id.')
    ..writeln('const kA64UpInstNames = <String>[');
  for (final r in rows) {
    sb.writeln("  '${r[0] == 'None' ? '' : r[0].toLowerCase()}',");
  }
  sb
    ..writeln('];')
    ..writeln()
    ..writeln('/// `InstDB::_inst_info_table` (encoding, encoding data index, '
        'RW info, flags).')
    ..writeln('const kA64UpInstInfo = <A64UpInstInfo>[');
  for (final r in rows) {
    final enc = A64Encoding.names.indexOf(r[1]);
    if (enc < 0) throw FormatException('encoding ${r[1]}');
    final flags = r[3] == '0'
        ? '0'
        : r[3]
            .split('|')
            .map((f) => 'kInstFlag${RegExp(r'F\((\w+)\)').firstMatch(f)![1]}')
            .join(' | ');
    sb.writeln('  A64UpInstInfo($enc, ${r[4]}, ${r[2]}, $flags), // ${r[0]}');
  }
  sb.writeln('];');

  // EncodingData arrays: `const T name[N] = { { a, b }, // comment ... };`
  final data = File(dataPath).readAsStringSync();
  final array = RegExp(r'^const (\w+) (\w+)\[\d+\] = \{\n(.*?)^\};',
      multiLine: true, dotAll: true);
  var arrays = 0;
  for (final m in array.allMatches(data)) {
    sb
      ..writeln()
      ..writeln('const ${m[2]} = <${m[1]}>[');
    for (final line in m[3]!.split('\n')) {
      final e = RegExp(r'^\s*\{(.*)\}\s*,?\s*(//.*)?$').firstMatch(line);
      if (e == null) continue;
      final values = e[1]!.split(',').map(value).join(', ');
      sb.writeln('  ${m[1]}($values), ${e[2] ?? ''}');
    }
    sb.writeln('];');
    arrays++;
  }
  File(_out).writeAsStringSync(sb.toString());
  stdout.writeln('Generated $_out (${rows.length} instructions, '
      '$arrays encoding data arrays)');
}
