String hex(List<int> b) =>
    b.map((e) => e.toRadixString(16).padLeft(2, '0')).join();

Map<String, String> _encodeAll() {
  final out = <String, String>{};
  final ids = {for (final i in kX86InstDb) i.name: i.id};
  final x9 = X86Xmm(9), x10 = X86Xmm(10), x2 = X86Xmm(2), x1 = X86Xmm(1);
  final y9 = X86Ymm(9), y10 = X86Ymm(10), y2 = X86Ymm(2);
  final mem =
      X86Mem.baseIndexScale(X86Gp.r64(9), X86Gp.r64(0), 2, disp: 64, size: 16);
  void emit(String text, String name, List<Object> ops) {
    final id = ids[name];
    if (id == null) return;
    final code = CodeHolder(env: Environment.x64SysV());
    final asm = X86Assembler(code);
    try {
      x86Dispatch(asm, id, ops);
    } catch (e) {
      out[text] = 'ERR';
      return;
    }
    out[text] = hex(code.text.buffer.bytes);
  }

  String memSize(String n) {
    if (n.endsWith('ss')) return 'dword ptr';
    if (n.endsWith('sd') && n != 'pminsd' && n != 'pmaxsd') return 'qword ptr';
    return 'xmmword ptr';
  }

  const memText = '[r9 + 2*rax + 64]';
  kX86SimdOps.forEach((key, op) {
    if (key.endsWith('_i')) {
      final n = key.substring(0, key.length - 2);
      emit('$n xmm9, 3', n, [x9, 3]);
      emit('v$n xmm9, xmm2, 3', 'v$n', [x9, x2, 3]);
      emit('v$n ymm9, ymm2, 3', 'v$n', [y9, y2, 3]);
      return;
    }
    final n = key;
    final scalar = n.endsWith('ss') ||
        (n.endsWith('sd') && n != 'pminsd' && n != 'pmaxsd');
    switch (op.kind) {
      case X86SimdKind.rm:
        emit('$n xmm9, xmm2', n, [x9, x2]);
        emit('$n xmm1, ${memSize(n)} $memText', n, [x1, mem]);
        emit('v$n xmm9, xmm10, xmm2', 'v$n', [x9, x10, x2]);
        emit('v$n xmm1, xmm10, ${memSize(n)} $memText', 'v$n', [x1, x10, mem]);
        final countShift = RegExp(r'^ps(ll|rl|ra)[wdq]$').hasMatch(n);
        if (!scalar && !countShift) {
          emit('v$n ymm9, ymm10, ymm2', 'v$n', [y9, y10, y2]);
        }
        if (countShift) emit('v$n ymm9, ymm10, xmm2', 'v$n', [y9, y10, x2]);
      case X86SimdKind.rmi:
        emit('$n xmm9, xmm2, 5', n, [x9, x2, 5]);
        emit('v$n xmm9, xmm10, xmm2, 5', 'v$n', [x9, x10, x2, 5]);
      case X86SimdKind.rm2:
        emit('$n xmm9, xmm2', n, [x9, x2]);
        emit('v$n xmm9, xmm2', 'v$n', [x9, x2]);
      case X86SimdKind.rm2i:
        emit('$n xmm9, xmm2, 5', n, [x9, x2, 5]);
        emit('v$n xmm9, xmm2, 5', 'v$n', [x9, x2, 5]);
      case X86SimdKind.shiftImm:
        break;
    }
  });
  return out;
}

